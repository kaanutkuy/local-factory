"""Core domain models shared by every local-factory module.

Orchestrator-owned: implementers import from here but do not edit this file.
All models are immutable; the ledger returns fresh snapshots after every change.
"""

from __future__ import annotations

from datetime import datetime
from enum import StrEnum
from pathlib import Path
from typing import Literal, Self

from pydantic import BaseModel, ConfigDict, Field, JsonValue, model_validator

SHA_PATTERN = r"^[0-9a-f]{40}([0-9a-f]{24})?$"
HASH_TAG_PATTERN = r"^sha256:[0-9a-f]{64}$"
TICKET_ID_PATTERN = r"^T-[0-9]{4,}$"
TASK_ID_PATTERN = r"^T-[0-9]{4,}/task-[0-9]+$"


class FrozenModel(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid", allow_inf_nan=False)


# --------------------------------------------------------------------------- tickets


class TicketType(StrEnum):
    BUG = "bug"
    FEATURE = "feature"
    CHORE = "chore"


class RiskTier(StrEnum):
    R0 = "R0"  # docs, config, copy
    R1 = "R1"  # normal product changes
    R2 = "R2"  # auth, payments, data, migrations


class TicketStatus(StrEnum):
    RECEIVED = "received"
    TRIAGED = "triaged"
    NEEDS_INFO = "needs_info"
    CONTRACT_PROPOSED = "contract_proposed"
    APPROVED = "approved"
    PLANNED = "planned"
    BUILDING = "building"
    VERIFYING = "verifying"
    CONVERGED = "converged"
    CANDIDATE_VERIFIED = "candidate_verified"
    MERGED = "merged"
    AWAITING_RELEASE_APPROVAL = "awaiting_release_approval"
    DEPLOYING = "deploying"
    DONE = "done"
    HALTED = "halted"
    BLOCKED = "blocked"
    ROLLED_BACK = "rolled_back"
    ABANDONED = "abandoned"


class MigrationImpact(StrEnum):
    NONE = "none"
    EXPAND_ONLY = "expand-only"
    DESTRUCTIVE = "destructive"


class TestLayer(StrEnum):
    __test__ = False  # not a pytest test class

    UNIT = "unit"
    INTEGRATION = "integration"
    E2E = "e2e"


class Criterion(FrozenModel):
    id: str = Field(pattern=r"^AC-[0-9]+$")
    ears: str = Field(min_length=1)
    layer: TestLayer
    tests: tuple[str, ...] = ()
    holdout_probes: int = Field(default=0, ge=0)


class Contract(FrozenModel):
    version: int = Field(ge=1)
    summary: str = Field(min_length=1)
    criteria: tuple[Criterion, ...] = Field(min_length=1)
    nfr: tuple[str, ...] = ()
    out_of_scope: tuple[str, ...] = ()
    assumptions: tuple[str, ...] = ()
    migration_impact: MigrationImpact = MigrationImpact.NONE

    @model_validator(mode="after")
    def _unique_criterion_ids(self) -> Self:
        ids = [c.id for c in self.criteria]
        if len(ids) != len(set(ids)):
            raise ValueError(f"duplicate criterion ids: {sorted(ids)}")
        return self


class Ticket(FrozenModel):
    """A snapshot of a ticket. The ledger is the source of truth."""

    id: str = Field(pattern=TICKET_ID_PATTERN)
    title: str = Field(min_length=1)
    type: TicketType
    risk: RiskTier
    status: TicketStatus
    request: str
    contract: Contract | None = None
    contract_hash: str | None = Field(default=None, pattern=HASH_TAG_PATTERN)  # set when frozen
    oracle_version: str | None = Field(default=None, pattern=HASH_TAG_PATTERN)
    created_at: datetime
    updated_at: datetime


# --------------------------------------------------------------------------- tasks & runs


class Tier(StrEnum):
    FAST = "fast"
    STANDARD = "standard"
    FRONTIER = "frontier"
    APEX = "apex"


class TaskStatus(StrEnum):
    PENDING = "pending"
    RUNNING = "running"
    SUBMITTED = "submitted"  # bundle produced, awaiting import + policy
    ACCEPTED = "accepted"  # imported, passed policy, integrated
    REJECTED = "rejected"
    HALTED = "halted"


class Task(FrozenModel):
    id: str = Field(pattern=TASK_ID_PATTERN)
    ticket_id: str = Field(pattern=TICKET_ID_PATTERN)
    goal: str = Field(min_length=1)
    criteria_served: tuple[str, ...] = ()
    depends_on: tuple[str, ...] = ()
    role: str = Field(min_length=1)
    tier: Tier
    status: TaskStatus = TaskStatus.PENDING
    base_sha: str | None = Field(default=None, pattern=SHA_PATTERN)
    head_sha: str | None = Field(default=None, pattern=SHA_PATTERN)


class HaltReason(StrEnum):
    """Why a run stopped without failing. A halt is never the worker's fault and never burns a
    round; the scheduler resumes the ticket (at ``Halt.resume_at`` when known)."""

    RATE_LIMIT = "rate_limit"  # the provider's rate limit outlasted the SDK's retries
    BILLING = "billing"  # the provider refused for billing or spend-limit reasons
    BUDGET = "budget"  # the factory's own budget for the run or ticket is spent
    MAX_TURNS = "max_turns"  # the role's turn cap was reached
    AUTH = "auth"  # no usable credential: missing, invalid, or lacking permission
    UNAVAILABLE = "unavailable"  # overloaded, server or connection errors outlasted the retries


class Halt(FrozenModel):
    reason: HaltReason
    resume_at: datetime | None = None
    detail: str = ""


class Usage(FrozenModel):
    input_tokens: int = Field(default=0, ge=0)
    output_tokens: int = Field(default=0, ge=0)
    cache_read_tokens: int = Field(default=0, ge=0)
    cache_write_tokens: int = Field(default=0, ge=0)
    cost_usd: float = Field(default=0.0, ge=0.0)


RunStatus = Literal["ok", "error", "halted"]


class RunRecord(FrozenModel):
    """One agent invocation, as recorded in the ledger."""

    id: str = Field(min_length=1)
    ticket_id: str = Field(pattern=TICKET_ID_PATTERN)
    task_id: str | None = Field(default=None, pattern=TASK_ID_PATTERN)
    role: str
    backend: str
    model: str
    tier: Tier
    started_at: datetime
    finished_at: datetime
    status: RunStatus
    usage: Usage = Usage()
    session_id: str | None = None
    transcript_path: Path | None = None
    error: str | None = None  # set when status is "error": what went wrong, for the ledger


# --------------------------------------------------------------------------- verification


class GateStatus(StrEnum):
    PASS = "pass"  # noqa: S105 - a status value, not a credential
    FAIL = "fail"
    ERROR = "error"
    SKIPPED = "skipped"
    WAIVED = "waived"


class GateResult(FrozenModel):
    name: str = Field(min_length=1)
    status: GateStatus
    exit_code: int | None = None
    duration_s: float = Field(default=0.0, ge=0.0)
    output_tail: str = ""
    metrics: dict[str, float] = Field(default_factory=dict)


class CriterionStatus(StrEnum):
    PASS = "pass"  # noqa: S105 - a status value, not a credential
    FAIL = "fail"
    INCONCLUSIVE = "inconclusive"


class CriterionResult(FrozenModel):
    id: str = Field(pattern=r"^AC-[0-9]+$")
    status: CriterionStatus
    evidence: str = ""
    feedback: str = ""
    holdout_hint: str | None = None


class Waiver(FrozenModel):
    """A request to accept a specific, scoped shortfall. Only effective once adjudicated.

    `scope` is gate-specific, e.g. "src/app.py:42" for a suppression or a mutant id.
    """

    id: str = Field(pattern=r"^W-[0-9]+$")
    gate: str = Field(min_length=1)
    scope: str = Field(min_length=1)
    reason: str = Field(min_length=1)
    requested_by: str = Field(min_length=1)
    adjudicated_by: str | None = None
    approved: bool = False

    @property
    def is_effective(self) -> bool:
        """Approved by someone other than the requester (the verifier, never the implementer)."""
        return (
            self.approved
            and self.adjudicated_by is not None
            and self.adjudicated_by != self.requested_by
        )


class AggregateResult(FrozenModel):
    passed: bool
    failing: tuple[str, ...]  # e.g. "gate:lint", "criterion:AC-3", "criteria:none"


class Verdict(FrozenModel):
    ticket_id: str = Field(pattern=TICKET_ID_PATTERN)
    round: int = Field(ge=1)
    sha: str = Field(pattern=SHA_PATTERN)
    gates: tuple[GateResult, ...]
    criteria: tuple[CriterionResult, ...]
    waivers: tuple[Waiver, ...] = ()
    passed: bool
    failing: tuple[str, ...] = ()


# --------------------------------------------------------------------------- git & policy


class ChangeKind(StrEnum):
    ADDED = "A"
    MODIFIED = "M"
    DELETED = "D"
    RENAMED = "R"
    TYPE_CHANGED = "T"


MODE_REGULAR = "100644"
MODE_EXECUTABLE = "100755"
MODE_SYMLINK = "120000"
MODE_GITLINK = "160000"


class AddedLine(FrozenModel):
    line_no: int = Field(ge=1)
    text: str


class ChangedFile(FrozenModel):
    path: str = Field(min_length=1)  # new path (the old path for deletions)
    kind: ChangeKind
    old_path: str | None = None  # set for renames
    mode: str | None = None  # new git mode; None for deletions
    old_mode: str | None = None
    size: int | None = Field(default=None, ge=0)  # bytes of the new blob
    is_binary: bool = False
    symlink_target: str | None = None  # set when mode == MODE_SYMLINK
    added_lines: tuple[AddedLine, ...] = ()


class Violation(FrozenModel):
    rule: str = Field(min_length=1)
    path: str
    line: int | None = None
    message: str = Field(min_length=1)


# ------------------------------------------------------------------- ledger events & evidence


class Event(FrozenModel):
    seq: int = Field(ge=1)
    ticket_id: str | None = Field(default=None, pattern=TICKET_ID_PATTERN)
    at: datetime
    kind: str = Field(min_length=1)
    actor: str = Field(min_length=1)
    from_status: TicketStatus | None = None
    to_status: TicketStatus | None = None
    data: dict[str, JsonValue] = Field(default_factory=dict)


class Evidence(FrozenModel):
    """Everything a release decision rests on, bound to one exact candidate."""

    schema_version: Literal[1] = 1
    ticket_id: str = Field(pattern=TICKET_ID_PATTERN)
    candidate_sha: str = Field(pattern=SHA_PATTERN)
    tree_hash: str = Field(pattern=SHA_PATTERN)
    base_sha: str = Field(pattern=SHA_PATTERN)
    contract_hash: str = Field(pattern=HASH_TAG_PATTERN)
    oracle_version: str = Field(pattern=HASH_TAG_PATTERN)
    factory_version: str = Field(min_length=1)
    image_digests: dict[str, str] = Field(default_factory=dict)
    models: dict[str, str] = Field(default_factory=dict)  # role -> model id
    gates: tuple[GateResult, ...]
    criteria: tuple[CriterionResult, ...]
    waivers: tuple[Waiver, ...] = ()
    passed: bool
    created_at: datetime
